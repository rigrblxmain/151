local function MXLGW_fake_script() -- R.UIDrag 
	local script = Instance.new('LocalScript', R)

	-- Made by Real_IceyDev (@lceyDex) --
	-- Enhanced UI dragger with physical lean effect (PC Only/Any device that has a mouse) --
	
	local UIS = game:GetService('UserInputService')
	local TweenService = game:GetService('TweenService')
	local frame = script.Parent
	local dragToggle = nil
	local dragSpeed = 0.25
	local dragStart = nil
	local startPos = nil
	local lastInputPos = nil
	local lastDragTime = nil
	local maxLeanAngle = 100 -- degrees, max lean angle (updated from 25 to 80)
	local leanTween = nil
	local minLeanSpeed = 7 -- minimum speed required to lean
	
	-- Find the lua ring child (ImageLabel)
	local luaRing = frame:FindFirstChild("lua ring")
	
	local function updateInput(input)
		local delta = input.Position - dragStart
		local position = UDim2.new(startPos.X.Scale, startPos.X.Offset + delta.X,
			startPos.Y.Scale, startPos.Y.Offset + delta.Y)
		TweenService:Create(frame, TweenInfo.new(dragSpeed), {Position = position}):Play()
	
		-- Calculate drag velocity for lean
		local now = tick()
		if lastInputPos and lastDragTime then
			local dragDelta = input.Position - lastInputPos
			local dt = now - lastDragTime
			if dt > 0 then
				local velocity = dragDelta / dt
				-- Only lean if horizontal drag speed is at least minLeanSpeed
				if math.abs(velocity.X) >= minLeanSpeed then
					local angle = math.clamp(velocity.X * 0.08, -maxLeanAngle, maxLeanAngle)
					if leanTween then leanTween:Cancel() end
					leanTween = TweenService:Create(frame, TweenInfo.new(0.15, Enum.EasingStyle.Quad, Enum.EasingDirection.Out), {Rotation = angle})
					leanTween:Play()
				else
					-- If speed is below threshold, keep Rotation at 0
					if leanTween then leanTween:Cancel() end
					leanTween = TweenService:Create(frame, TweenInfo.new(0.15, Enum.EasingStyle.Quad, Enum.EasingDirection.Out), {Rotation = 0})
					leanTween:Play()
				end
			end
		end
		lastInputPos = input.Position
		lastDragTime = now
	end
	
	local function resetLean()
		if leanTween then leanTween:Cancel() end
		leanTween = TweenService:Create(frame, TweenInfo.new(0.8, Enum.EasingStyle.Quad, Enum.EasingDirection.Out), {Rotation = 0}) -- Slower lean back
		leanTween:Play()
	end
	
	frame.InputBegan:Connect(function(input)
		if (input.UserInputType == Enum.UserInputType.MouseButton1 or input.UserInputType == Enum.UserInputType.Touch) then 
			dragToggle = true
			dragStart = input.Position
			startPos = frame.Position
			lastInputPos = input.Position
			lastDragTime = tick()
			input.Changed:Connect(function()
				if input.UserInputState == Enum.UserInputState.End then
					dragToggle = false
					resetLean()
				end
			end)
		end
	end)
	
	UIS.InputChanged:Connect(function(input)
		if input.UserInputType == Enum.UserInputType.MouseMovement or input.UserInputType == Enum.UserInputType.Touch then
			if dragToggle then
				updateInput(input)
			end
		end
	end)
	
	
end
