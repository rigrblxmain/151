local function YHIU_fake_script() -- mian.PlayerListPopulator 
	local script = Instance.new('LocalScript', mian)

	local Players = game:GetService("Players")
	local ReplicatedStorage = game:GetService("ReplicatedStorage")
	local mian = script.Parent
	local playerholderTemplate = mian:FindFirstChild("playerholder")
	
	playerholderTemplate.Visible = false  -- Hide the template itself
	
	-- Helper to create a playerholder for a player
	local function createPlayerHolder(player)
	    local holder = playerholderTemplate:Clone()
	    holder.Name = player.Name .. "_holder"
	    holder.Visible = true
	
	    local usernameLabel = holder:FindFirstChild("Username")
	    if usernameLabel then
	        usernameLabel.Text = "@"..player.Name
	    end
	
	    local displaynameLabel = holder:FindFirstChild("displayname")
	    if displaynameLabel then
	        displaynameLabel.Text = player.DisplayName
	    end
	
	    -- Set player headshot image
	    local userId = player.UserId
	    local thumbType = Enum.ThumbnailType.HeadShot
	    local thumbSize = Enum.ThumbnailSize.Size100x100
	    local thumbUrl, isReady = Players:GetUserThumbnailAsync(userId, thumbType, thumbSize)
	    holder.Image = thumbUrl
	end
	
	-- Remove all holders except the template
	local function clearPlayerHolders()
	    for i, child in mian:GetChildren() do
	        if child ~= playerholderTemplate and child:IsA("ImageLabel") then
	            child:Destroy()
	        end
	    end
	end
	
	-- Helper to reposition playerholders to avoid overlap
	local function repositionPlayerHolders()
	    local yOffset = 0
	    local spacing = 10 -- pixels between holders
	    local holderHeight = playerholderTemplate.AbsoluteSize.Y > 0 and playerholderTemplate.AbsoluteSize.Y or 50
	    for i, child in mian:GetChildren() do
	        if child ~= playerholderTemplate and child:IsA("ImageLabel") and child.Visible then
	            child.Position = UDim2.new(child.Position.X.Scale, child.Position.X.Offset, 0, yOffset)
	            yOffset = yOffset + holderHeight + spacing
	        end
	    end
	end
	
	-- Refresh the player list
	local function refreshPlayerList()
	    clearPlayerHolders()
	    -- Add all players, including the local player (self)
	    for i, player in Players:GetPlayers() do
	        createPlayerHolder(player)
	    end
	    -- Ensure local player is included even if not in GetPlayers() yet
	    local localPlayer = Players.LocalPlayer
	    local foundSelf = false
	    for i, player in Players:GetPlayers() do
	        if player == localPlayer then
	            foundSelf = true
	            break
	        end
	    end
	    if not foundSelf and localPlayer then
	        createPlayerHolder(localPlayer)
	    end
	    -- After creating holders, reposition them to avoid overlap
	    repositionPlayerHolders()
	end
	
	-- Listen for player join/leave
	Players.PlayerAdded:Connect(function(player)
	    refreshPlayerList()
	end)
	
	Players.PlayerRemoving:Connect(function(player)
	    refreshPlayerList()
	end)
	
	-- Initial population
	refreshPlayerList()
end
