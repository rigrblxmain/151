local function MXWJ_fake_script() -- R.RButtonAppearFromRandom 
	local script = Instance.new('LocalScript', R)

	local button = script.Parent
	local TweenService = game:GetService("TweenService")
	
	-- Save the original position
	local originalPos = button.Position
	
	-- Generate a random off-screen position
	local function getOffScreenPosition()
	    local parent = button.Parent
	    local parentSize = parent.AbsoluteSize
	    local buttonSize = button.AbsoluteSize
	
	    -- Choose a random side: 1=left, 2=right, 3=top, 4=bottom
	    local side = math.random(1, 4)
	    local posX, posY
	
	    if side == 1 then
	        -- Left
	        posX = -buttonSize.X
	        posY = math.random(0, parentSize.Y - buttonSize.Y)
	    elseif side == 2 then
	        -- Right
	        posX = parentSize.X
	        posY = math.random(0, parentSize.Y - buttonSize.Y)
	    elseif side == 3 then
	        -- Top
	        posX = math.random(0, parentSize.X - buttonSize.X)
	        posY = -buttonSize.Y
	    else
	        -- Bottom
	        posX = math.random(0, parentSize.X - buttonSize.X)
	        posY = parentSize.Y
	    end
	
	    -- Convert absolute position to UDim2 relative to parent
	    return UDim2.new(0, posX, 0, posY)
	end
	
	-- Calculate center position of parent for the button
	local function getCenterPosition()
	    local parent = button.Parent
	    local parentSize = parent.AbsoluteSize
	    local buttonSize = button.AbsoluteSize
	
	    local centerX = (parentSize.X - buttonSize.X) / 2
	    local centerY = (parentSize.Y - buttonSize.Y) / 2
	
	    return UDim2.new(0, centerX, 0, centerY)
	end
	
	task.spawn(function()
	    -- Move to off-screen position instantly
	    button.Position = getOffScreenPosition()
	    -- Wait 2 seconds
	    task.wait(2)
	    -- Tween to center of screen
	    local tweenToCenter = TweenService:Create(button, TweenInfo.new(0.6, Enum.EasingStyle.Quad, Enum.EasingDirection.Out), {Position = getCenterPosition()})
	    tweenToCenter:Play()
	    tweenToCenter.Completed:Wait(0.5)
	    -- Tween to original position
	    TweenService:Create(button, TweenInfo.new(0.6, Enum.EasingStyle.Quad, Enum.EasingDirection.Out), {Position = originalPos}):Play()
	end)
	
	
end
